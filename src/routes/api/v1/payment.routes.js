import { Router } from "express";
import authenticate from "../../../middlewares/auth.middleware.js";
import {
  getStats,
  getPayments,
  getPayment,
} from "../../../controllers/payment.controller.js";

const router = Router();
router.use(authenticate);

//////////////////////////////////////////////////////////////
// PAYMENT STATS
//////////////////////////////////////////////////////////////

router.get(
  "/stats",
  getStats
);

//////////////////////////////////////////////////////////////
// GET ALL PAYMENTS
//////////////////////////////////////////////////////////////

router.get(
  "/",
  getPayments
);

//////////////////////////////////////////////////////////////
// GET PAYMENT BY ID
//////////////////////////////////////////////////////////////

router.get(
  "/:id",
  getPayment
);

export default router;